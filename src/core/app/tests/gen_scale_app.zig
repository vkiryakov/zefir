//! Writes an application of zefir.App at scale, which `zig build test-core`
//! compiles and never runs, to keep App's compile time in check:
//!
//! - module i imports modules i-1 and i-2;
//! - each module has providers of four shapes in turn: an init that takes
//!   a struct of dependencies, an init that takes params, a struct App
//!   fills (with a copy of a value and a field with a default), and a
//!   struct App fills that has a lifecycle;
//! - each module has controllers, each taking a provider of its module, an
//!   export of an import and a value, and a factories struct of two
//!   functions, one of which returns `!T`;
//! - each module exports its last provider and its first factory result,
//!   and its first two providers take those of its imports;
//! - the root imports every module and builds one server with a factory
//!   that takes `zefir.app.Controllers(Big)`; its values are `*Counter` and
//!   `*const Config`.
//!
//!     app-gen-scale <modules> <providers> <controllers> <out.zig>
//!
//! `zig build test-core` writes and compiles 10 × 20 × 10;
//! `zig build app-gen-scale -- 50 20 10 <out.zig>` writes a larger one to
//! measure by hand. A host program of the build; a panic exits with code 3
//! instead of aborting.
const std = @import("std");

pub const panic = std.debug.FullPanic(exitOnPanic);

fn exitOnPanic(message: []const u8, _: ?usize) noreturn {
    std.debug.print("panic: {s}\n", .{message});
    std.process.exit(3);
}

const Size = struct { modules: usize, providers: usize, controllers: usize };

pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    const size: ?Size = if (args.len != 5) null else .{
        .modules = std.fmt.parseUnsigned(usize, args[1], 10) catch 0,
        .providers = std.fmt.parseUnsigned(usize, args[2], 10) catch 0,
        .controllers = std.fmt.parseUnsigned(usize, args[3], 10) catch 0,
    };
    if (size == null or size.?.modules == 0 or size.?.providers == 0) {
        std.debug.print("usage: app-gen-scale <modules> <providers> <controllers> <out.zig>; modules and providers at least 1\n", .{});
        std.process.exit(2);
    }
    var out: std.Io.Writer.Allocating = .init(init.arena.allocator());
    try write(&out.writer, size.?);
    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[4], .data = out.written() });
}

fn write(w: *std.Io.Writer, size: Size) !void {
    try w.print(
        \\//! Generated by src/core/app/tests/gen_scale_app.zig: an application of
        \\//! zefir.App of {d} modules, each of {d} providers and {d} controllers,
        \\//! which `zig build test-core` compiles and never runs. It holds no
        \\//! @setEvalBranchQuota: App sets its own.
        \\
    , .{ size.modules, size.providers, size.controllers });
    try w.writeAll(
        \\const std = @import("std");
        \\const core = @import("core");
        \\const app = core.app;
        \\const Io = std.Io;
        \\
        \\pub const Counter = struct { inits: u32 = 0, starts: u32 = 0, stops: u32 = 0, deinits: u32 = 0 };
        \\pub const Config = struct { name: []const u8 = "big" };
        \\
        \\fn Life(comptime Self: type) type {
        \\    return struct {
        \\        pub fn start(s: *Self, _: Io) !void {
        \\            s.counter.starts += 1;
        \\        }
        \\        pub fn shutdown(s: *Self, _: Io, _: Io.Clock.Timestamp) !void {
        \\            s.counter.stops += 1;
        \\        }
        \\        pub fn deinit(s: *Self) void {
        \\            s.counter.deinits += 1;
        \\        }
        \\    };
        \\}
        \\
        \\pub const Server = struct {
        \\    counter: *Counter,
        \\    gpa: std.mem.Allocator,
        \\    controllers: []*anyopaque,
        \\
        \\    pub fn init(gpa: std.mem.Allocator, counter: *Counter, parts: anytype) !Server {
        \\        const n = @typeInfo(@TypeOf(parts.controllers)).@"struct".field_types.len;
        \\        const list = try gpa.alloc(*anyopaque, n);
        \\        inline for (parts.controllers, 0..) |c, k| list[k] = c;
        \\        return .{ .counter = counter, .gpa = gpa, .controllers = list };
        \\    }
        \\    pub const start = Life(Server).start;
        \\    pub const shutdown = Life(Server).shutdown;
        \\    pub fn deinit(s: *Server) void {
        \\        s.counter.deinits += 1;
        \\        s.gpa.free(s.controllers);
        \\    }
        \\};
        \\
        \\
    );
    for (0..size.modules) |i| {
        for (0..size.providers) |j| try writeProvider(w, size, i, j);
        for (0..size.controllers) |k| {
            try w.print("pub const M{d}C{d} = struct {{\n    service: *M{d}P{d},\n    config: *const Config,\n", .{ i, k, i, k % size.providers });
            if (i >= 1) try w.print("    up: *M{d}X0,\n", .{i - 1});
            try w.writeAll("    pub const http_routes = .{};\n};\n");
        }
        try w.print(
            \\pub const M{d}X0 = struct {{ first: *M{d}P0, counter: *Counter }};
            \\pub const M{d}X1 = struct {{ x0: *M{d}X0, name: []const u8 }};
            \\pub const M{d}F = struct {{
            \\    pub fn x0(first: *M{d}P0, counter: *Counter) M{d}X0 {{
            \\        return .{{ .first = first, .counter = counter }};
            \\    }}
            \\    pub fn x1(x0v: *M{d}X0, config: *const Config) !M{d}X1 {{
            \\        return .{{ .x0 = x0v, .name = config.name }};
            \\    }}
            \\}};
            \\pub const M{d} = struct {{
            \\    pub const module: app.Module = .{{
            \\        .imports = &.{{
        , .{ i, i, i, i, i, i, i, i, i, i });
        if (i >= 1) try w.print(" M{d}", .{i - 1});
        if (i >= 2) try w.print(", M{d}", .{i - 2});
        try w.writeAll(" },\n        .providers = &.{");
        for (0..size.providers) |j| try w.print("{s} M{d}P{d}", .{ if (j == 0) "" else ",", i, j });
        try w.writeAll(" },\n        .controllers = &.{");
        for (0..size.controllers) |k| try w.print("{s} M{d}C{d}", .{ if (k == 0) "" else ",", i, k });
        try w.print(
            \\ }},
            \\        .factories = &.{{M{d}F}},
            \\        .exports = &.{{ M{d}P{d}, M{d}X0 }},
            \\    }};
            \\}};
            \\
            \\
        , .{ i, i, size.providers - 1, i });
    }
    try w.writeAll(
        \\pub const Big = struct {
        \\    pub const module: app.Module = .{
        \\        .imports = &.{
    );
    for (0..size.modules) |i| try w.print("{s} M{d}", .{ if (i == 0) "" else ",", i });
    try w.writeAll(
        \\ },
        \\        .factories = &.{Servers},
        \\        .values = &.{ *Counter, *const Config },
        \\    };
        \\
        \\    pub const Servers = struct {
        \\        pub fn server(gpa: std.mem.Allocator, counter: *Counter, controllers: app.Controllers(Big)) !Server {
        \\            return Server.init(gpa, counter, .{ .controllers = controllers });
        \\        }
        \\    };
        \\};
        \\
        \\
    );
    // Shapes 0 and 1 count their init; every shape but 2 has a deinit, and
    // so has the server.
    var inits: usize = 0;
    var deinits: usize = 1;
    for (0..size.providers) |j| {
        if (j % 4 < 2) inits += size.modules;
        if (j % 4 != 2) deinits += size.modules;
    }
    try w.print(
        \\test "zefir.App at scale: {d} modules, each of {d} providers and {d} controllers" {{
        \\    var counter: Counter = .{{}};
        \\    const config: Config = .{{}};
        \\    var a = try core.App(Big).init(std.testing.allocator, std.testing.io, .{{ &config, &counter }}, .{{}});
        \\    try std.testing.expectEqual(@as(usize, {d}), a.get(Server).controllers.len);
        \\    try std.testing.expectEqual(@as(u32, {d}), counter.inits);
        \\    a.deinit();
        \\    try std.testing.expectEqual(@as(u32, {d}), counter.deinits);
        \\}}
        \\
    , .{ size.modules, size.providers, size.controllers, size.modules * size.controllers, inits, deinits });
}

/// Provider j of module i, of shape j % 4. Its first field after the
/// counter is the provider before it (or the counter); providers 0 and 1
/// also take the last provider of import i-1 or i-2.
fn writeProvider(w: *std.Io.Writer, size: Size, i: usize, j: usize) !void {
    var prev_buf: [32]u8 = undefined;
    const prev = if (j > 0) try std.fmt.bufPrint(&prev_buf, "*M{d}P{d}", .{ i, j - 1 }) else "*Counter";
    var up_buf: [32]u8 = undefined;
    const up: ?[]const u8 = if (j == 0 and i >= 1)
        try std.fmt.bufPrint(&up_buf, "*M{d}P{d}", .{ i - 1, size.providers - 1 })
    else if (j == 1 and i >= 2)
        try std.fmt.bufPrint(&up_buf, "*M{d}P{d}", .{ i - 2, size.providers - 1 })
    else
        null;
    try w.print("pub const M{d}P{d} = struct {{\n    counter: *Counter,\n    prev: {s},\n", .{ i, j, prev });
    switch (j % 4) {
        0 => {
            if (up) |u| try w.print("    up: {s},\n", .{u});
            try w.print("    pub fn init(deps: struct {{ counter: *Counter, prev: {s}", .{prev});
            if (up) |u| try w.print(", up: {s}", .{u});
            try w.print(" }}) M{d}P{d} {{\n        deps.counter.inits += 1;\n        return .{{ .counter = deps.counter, .prev = deps.prev", .{ i, j });
            if (up != null) try w.writeAll(", .up = deps.up");
            try w.print(" }};\n    }}\n    pub const deinit = Life(M{d}P{d}).deinit;\n", .{ i, j });
        },
        1 => {
            try w.writeAll("    config: *const Config,\n");
            if (up) |u| try w.print("    up: {s},\n", .{u});
            try w.print("    pub fn init(counter: *Counter, prev: {s}, config: *const Config", .{prev});
            if (up) |u| try w.print(", up: {s}", .{u});
            try w.print(") !M{d}P{d} {{\n        counter.inits += 1;\n        return .{{ .counter = counter, .prev = prev, .config = config", .{ i, j });
            if (up != null) try w.writeAll(", .up = up");
            try w.print(" }};\n    }}\n    pub const deinit = Life(M{d}P{d}).deinit;\n", .{ i, j });
        },
        2 => {
            try w.writeAll("    config: Config,\n");
            if (up) |u| try w.print("    up: {s},\n", .{u});
            try w.writeAll("    hits: u32 = 0,\n");
        },
        else => {
            if (up) |u| try w.print("    up: {s},\n", .{u});
            try w.print(
                \\    pub const start = Life(M{d}P{d}).start;
                \\    pub const shutdown = Life(M{d}P{d}).shutdown;
                \\    pub const deinit = Life(M{d}P{d}).deinit;
                \\
            , .{ i, j, i, j, i, j });
        },
    }
    try w.writeAll("};\n");
}
